#!/usr/bin/env python3
"""Grep-level checks for Nix anti-patterns that nixpkgs reviewers commonly correct.

It needs only Python 3, no Nix. It's a fast first gate, not a parser: every rule is
a text pattern, so some report false positives (each message says how to judge).
Rules are numbered by area: NL language style, TS testing, FS fetchers, MT meta,
DV derivations, PY/GO/RS language builders, SC security, MOD NixOS modules, BP
build and platforms. `--list-rules` prints them with the reference that explains each.

Usage:
  antipatterns.py [--strict] [--json] [--ignore ID,...] PATH...
  antipatterns.py --list-rules

Exit status: 0 no errors (warnings allowed), 1 errors found (or any finding with
--strict), 2 usage error. Suppress a finding with a comment on the same or the
previous line:  # antipatterns: ignore NL02   (file-wide: # antipatterns: ignore-file NL02)
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path

SKIP_DIRS = {".git", "result", "node_modules", ".direnv", "__pycache__"}
# Tool-generated lock/dependency expressions repeat legacy forms by design.
GENERATED_NAMES = {"gemset.nix", "node-packages.nix", "deps.nix", "generated.nix", "default-generated.nix"}
GENERATED_HEADER_RE = re.compile(r"(?i)auto-?generated|generated by|do not edit")
IGNORE_RE = re.compile(r"antipatterns:\s*ignore(-file)?\s+([A-Z0-9][A-Z0-9,\s]*)")


@dataclass(frozen=True)
class Rule:
    id: str
    severity: str  # "error" blocks; "warn" needs a human look
    message: str
    ref: str  # reference file that explains the rule
    kind: str = "line"  # line | multi | file | phase | no_comment
    pattern: str = ""
    requires: str = ""  # file must match this for the rule to apply
    unless: str = ""  # file must NOT match this for the rule to apply
    lacks: str = ""  # kind=file: report only when the file lacks this


@dataclass(frozen=True)
class Finding:
    path: str
    line: int
    rule: str
    severity: str
    message: str
    reference: str
    text: str = ""


