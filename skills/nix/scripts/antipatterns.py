_COMPILED: dict[str, re.Pattern] = {}
PHASE_RE = re.compile(r"(?s)\b(build|install|check|configure|installCheck|patch|unpack)Phase\s*=\s*''(.*?)''\s*;")


def _rx(pattern: str) -> re.Pattern:
    if pattern not in _COMPILED:
        _COMPILED[pattern] = re.compile(pattern)
    return _COMPILED[pattern]


def code_view(text: str) -> str:
    """Text with whole-line comments blanked and trailing `# ...` comments removed,
    keeping line numbers intact."""
    out = []
    for line in text.split("\n"):
        stripped = line.lstrip()
        if stripped.startswith("#"):
            out.append("")
        else:
            out.append(re.sub(r"\s#\s.*$|\s#$", "", line))
    return "\n".join(out)


def _line_of(text: str, offset: int) -> int:
    return text.count("\n", 0, offset) + 1


def _suppressed(raw_lines: list[str], line: int, rule: str, file_ignores: set[str]) -> bool:
    if rule in file_ignores:
        return True
    for idx in (line - 1, line - 2):
        if 0 <= idx < len(raw_lines):
            m = IGNORE_RE.search(raw_lines[idx])
            if m and not m.group(1) and rule in re.split(r"[,\s]+", m.group(2).strip()):
                return True
    return False


def check_text(text: str, path: str = "<text>") -> list[Finding]:
    raw_lines = text.split("\n")
    code = code_view(text)
    code_lines = code.split("\n")
    file_ignores: set[str] = set()
    for m in IGNORE_RE.finditer(text):
        if m.group(1):
            file_ignores.update(re.split(r"[,\s]+", m.group(2).strip()))
    findings: list[Finding] = []

    def add(rule: Rule, line: int) -> None:
        if _suppressed(raw_lines, line, rule.id, file_ignores):
            return
        snippet = raw_lines[line - 1].strip() if 0 < line <= len(raw_lines) else ""
        findings.append(Finding(path, line, rule.id, rule.severity, rule.message, f"references/{rule.ref}", snippet))

    for rule in RULES:
        if rule.requires and not _rx(rule.requires).search(code):
            continue
        if rule.unless and _rx(rule.unless).search(code):
            continue
        if rule.kind in ("line", "no_comment"):
            rx = _rx(rule.pattern)
            for i, cl in enumerate(code_lines, 1):
                if rx.search(cl):
                    if rule.kind == "no_comment":
                        prev = raw_lines[i - 2].strip() if i >= 2 else ""
                        if "#" in raw_lines[i - 1] or prev.startswith("#"):
                            continue
                    add(rule, i)
        elif rule.kind == "multi":
            for m in _rx(rule.pattern).finditer(code):
                add(rule, _line_of(code, m.start()))
        elif rule.kind == "file":
            m = _rx(rule.pattern).search(code)
            if m and not _rx(rule.lacks).search(code):
                add(rule, _line_of(code, m.start()))
        elif rule.kind == "phase":
            for m in PHASE_RE.finditer(code):
                if "runHook" not in m.group(2):
                    add(rule, _line_of(code, m.start()))
    findings.sort(key=lambda f: (f.line, f.rule))
    return findings


def is_generated(path: Path, text: str) -> bool:
    return path.name in GENERATED_NAMES or bool(GENERATED_HEADER_RE.search("\n".join(text.split("\n")[:5])))


def iter_nix_files(paths: list[Path]):
    for p in paths:
        if p.is_file():
            if p.suffix == ".nix":
                yield p
        else:
            for f in sorted(p.rglob("*.nix")):
                if not SKIP_DIRS.intersection(f.parts):
                    yield f


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("paths", nargs="*", type=Path)
    ap.add_argument("--strict", action="store_true", help="fail on warnings too")
    ap.add_argument("--json", action="store_true", help="machine-readable output")
    ap.add_argument("--ignore", default="", help="comma-separated rule ids to skip")
    ap.add_argument("--list-rules", action="store_true")
    args = ap.parse_args(argv)

    if args.list_rules:
        for r in RULES:
            print(f"{r.id:6} {r.severity:5} {r.message}  [references/{r.ref}]")
        return 0
    if not args.paths:
        ap.error("give at least one file or directory")
    missing = [p for p in args.paths if not p.exists()]
    if missing:
        print(f"antipatterns: path not found: {missing[0]}", file=sys.stderr)
        return 2

    ignored = {i.strip() for i in args.ignore.split(",") if i.strip()}
    findings: list[Finding] = []
    for f in iter_nix_files(args.paths):
        try:
            text = f.read_text()
        except (OSError, UnicodeDecodeError) as exc:
            print(f"antipatterns: skipping {f}: {exc}", file=sys.stderr)
            continue
        if is_generated(f, text):
            continue
        findings += [x for x in check_text(text, str(f)) if x.rule not in ignored]

    if args.json:
        print(json.dumps([x.__dict__ for x in findings], indent=1))
    else:
        for x in findings:
            print(f"{x.path}:{x.line}: {x.severity} [{x.rule}] {x.message} ({x.reference})")
        errors = sum(x.severity == "error" for x in findings)
        print(f"antipatterns: {errors} error(s), {len(findings) - errors} warning(s)", file=sys.stderr)
    failing = [x for x in findings if x.severity == "error" or args.strict]
    return 1 if failing else 0


if __name__ == "__main__":
    sys.exit(main())
